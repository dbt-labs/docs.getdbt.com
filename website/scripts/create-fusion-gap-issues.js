/**
 * Diffs the newly-fetched platform function JSON against the previously
 * committed version and opens GitHub issues in dbt-labs/dbt-core for any
 * brand-new functions that are missing Fusion typechecking support.
 *
 * Runs inside update-platform-functions.yml, after fetch but before commit,
 * so the new JSON is on disk and the old JSON is still at HEAD.
 *
 * Usage:
 *   node scripts/create-fusion-gap-issues.js snowflake
 *
 * Env vars:
 *   FUSION_ISSUES_TOKEN  — PAT with issues:write on https://github.com/dbt-labs/dbt-core
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');
const { PLATFORMS } = require('./platforms.config');

const ISSUES_REPO = 'dbt-labs/dbt-core';
const ISSUE_LABEL = 'SQL_understanding';
const DATA_DIR = path.join(__dirname, '..', 'static', 'data', 'functions');

async function githubRequest(method, endpoint, body, token) {
  const res = await fetch(`https://api.github.com${endpoint}`, {
    method,
    headers: {
      'User-Agent': 'dbt-docs-bot/1.0',
      Accept: 'application/vnd.github+json',
      Authorization: `token ${token}`,
      'X-GitHub-Api-Version': '2022-11-28',
    },
    body: body ? JSON.stringify(body) : undefined,
  });
  if (!res.ok) {
    const text = await res.text();
    throw new Error(`GitHub API ${method} ${endpoint} → HTTP ${res.status}: ${text}`);
  }
  return res.json();
}

function getPreviousFunctions(platform) {
  try {
    const raw = execSync(
      `git show HEAD:website/static/data/functions/${platform}.json`,
      { encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe'] }
    );
    return JSON.parse(raw).functions || [];
  } catch {
    // File doesn't exist in HEAD yet (first run)
    return [];
  }
}

async function issueExists(title, token) {
  // Search for open issues with this exact title in the target repo
  const query = encodeURIComponent(`repo:${ISSUES_REPO} is:issue is:open in:title "${title}"`);
  const data = await githubRequest('GET', `/search/issues?q=${query}&per_page=1`, null, token);
  return data.total_count > 0;
}

async function createIssue(fn, platform, token) {
  const platformName = platform.charAt(0).toUpperCase() + platform.slice(1);
  const title = `[${platformName}] Add typechecking support for ${fn.name}`;
  const body = [
    `**Function:** [${fn.name}](${fn.docs_url})`,
    `**Category:** ${fn.category}`,
    `**Platform:** ${platformName}`,
    `**Preview status:** ${fn.preview_status}`,
    '',
    `This function was detected on the ${platformName} all-functions page but is not present in the Fusion typechecking support list (\`functions.sdf.yml\`).`,
    '',
    '_This issue was automatically generated by the [docs.getdbt.com function tracking workflow](https://github.com/dbt-labs/docs.getdbt.com/actions/workflows/update-platform-functions.yml)._',
  ].join('\n');

  await githubRequest('POST', `/repos/${ISSUES_REPO}/issues`, { title, body, labels: [ISSUE_LABEL] }, token);
  return title;
}

async function run(platformId) {
  const token = process.env.FUSION_ISSUES_TOKEN;
  if (!token) {
    console.warn('[gap-issues] FUSION_ISSUES_TOKEN not set — skipping issue creation');
    return;
  }

  const platform = PLATFORMS.find((p) => p.id === platformId);
  if (!platform) {
    console.error(`[gap-issues] Unknown platform: ${platformId}`);
    process.exit(1);
  }

  const dataPath = path.join(DATA_DIR, `${platformId}.json`);
  if (!fs.existsSync(dataPath)) {
    console.warn(`[gap-issues] ${dataPath} not found — skipping`);
    return;
  }

  const newFunctions = JSON.parse(fs.readFileSync(dataPath, 'utf8')).functions || [];
  const oldFunctions = getPreviousFunctions(platformId);
  const oldNames = new Set(oldFunctions.map((f) => f.name));

  // New gaps: functions added to the platform list that Fusion doesn't support yet
  const newGaps = newFunctions.filter((f) => !f.fusion_typecheck && !oldNames.has(f.name));

  if (newGaps.length === 0) {
    console.log(`[gap-issues][${platformId}] No new gaps detected`);
    return;
  }

  console.log(`[gap-issues][${platformId}] Found ${newGaps.length} new gap(s) — checking for existing issues...`);

  let created = 0;
  let skipped = 0;

  for (const fn of newGaps) {
    const platformName = platformId.charAt(0).toUpperCase() + platformId.slice(1);
    const title = `[${platformName}] Add typechecking support for ${fn.name}`;
    try {
      if (await issueExists(title, token)) {
        console.log(`  [skip] ${fn.name} — issue already exists`);
        skipped++;
      } else {
        await createIssue(fn, platformId, token);
        console.log(`  [created] ${fn.name}`);
        created++;
      }
    } catch (err) {
      console.error(`  [error] ${fn.name}: ${err.message}`);
    }
  }

  console.log(`[gap-issues][${platformId}] Done: ${created} created, ${skipped} skipped`);
}

const platformId = process.argv[2];
if (!platformId) {
  console.error('Usage: node create-fusion-gap-issues.js <platform>');
  process.exit(1);
}

run(platformId);
